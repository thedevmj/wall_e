/**
 * Bundled wallpaper catalog.
 *
 * Each entry explicitly requires() the asset so Metro bundles the file into the
 * app. The require()d value is kept in `source` so the UI can render it directly,
 * and `videoUri`/`imageUri` carry resolved copies used by the native bridge.
 */

function resolveUri(asset: unknown): string | undefined {
  return typeof asset === 'number' ? (Image.resolveAssetSource(asset)?.uri ?? undefined) : undefined;
}

